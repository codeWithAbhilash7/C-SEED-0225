#include <stdio.h>

void main()
{
    // format specifiers

    int iValue = 10;
    float fValue = 3.14;
    char chValue = 'A';
    double dValue = 123.456;

    printf("Integer Value is %d", iValue);
    printf("\nFloat Value is %f", fValue);
    printf("\nCharacter Value is %c", chValue);
    printf("\nDouble Value is %lf", dValue);
}